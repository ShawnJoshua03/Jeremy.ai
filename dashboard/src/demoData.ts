import type { DemoSession, Sample, SessionReplay } from "./types";

function samples(
  instrument: Sample["instrument"],
  points: Array<[number, number, number, number]>,
): Sample[] {
  return points.map(([t_ms, x, y, z], idx) => ({
    instrument,
    idx,
    t_ms,
    pos: [x, y, z],
    valid: true,
    interaction: idx % 4 === 0 ? "grasping" : "moving",
  }));
}

